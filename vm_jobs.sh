# ============================================================================
# VideoMind rebuild, Part 1b: durable processing jobs
# ============================================================================
# FOR THE rebuild BRANCH ONLY. It refuses to run on main.
#
# Until now a video was processed inside the upload request's process,
# tracked only in memory. A restart or deploy lost every video in
# progress, and any failure meant uploading again.
#
# After this part every stage (transcribe, analyze) is a row in a `jobs`
# table:
#   * a restart or deploy loses nothing: the next instance resumes
#   * a temporary failure is retried by itself, with a growing wait
#   * a stage that fails for good keeps its reason, and the owner can run
#     just that stage again; finished stages are not repeated or paid twice
#   * confirming an upload twice starts one job, not two
#
#   BACKEND   4 new files, 5 changed, 1 removed. One migration (jobs table,
#             videos.source_path), applied once when the service starts.
#   FRONTEND  3 changed: the processing panel names the failed step, shows
#             the owner why, and offers a retry.
#
# No new packages. No lockfile changes.
#
#   ./vm_jobs.sh            apply (needs Part 1a applied)
#   ./vm_jobs.sh --force    apply even if local files differ from GitHub
#   ./vm_jobs.sh --revert   restore everything from the latest backup
#
# Run from the repo root (dir containing backend/ and frontend/).
# ============================================================================
