  [ -n "$LATEST" ] || die "No backups found."
  restore_from "${LATEST%/}"
  say "Restored 8 changed files and 1 removed file, and removed 4 new files, from $LATEST"
  say "The database migration is not undone. The extra table and column are harmless to the older code."
  exit 0
fi

