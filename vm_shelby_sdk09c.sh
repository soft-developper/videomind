PRE_EX="098277755b5843c4c2a4e37873c885b16f8fb057d3743556d9b2b3f5eba641cd"

check_pre() {
  if [ "$(sha "$1")" != "$2" ]; then
    if [ "$FORCE" = "1" ]; then say "WARNING: $1 differs from GitHub (7d5888b). Overwriting (--force)."
    else die "$1 differs from the GitHub version this patch was built on (7d5888b). Nothing changed. Push or stash local edits, or re-run with --force."; fi
  fi
}
check_pre "$HK" "$PRE_HK"; check_pre "$PF" "$PRE_PF"; check_pre "$EX" "$PRE_EX"
if [ -f "$OC" ] && [ "$FORCE" != "1" ]; then
