# ============================================================================
# VideoMind - Shelby SDK 0.9 upgrade, Part 2a (On-chain proof panel)
# ============================================================================
# Fixes the On-chain proof panel on every video page:
#   Could not reach the indexer: field 'blobs' not found in type: 'query_root'
#
# Cause: the old indexer `blobs` table (with expires_at) no longer exists
# on Shelbynet. The panel now reads:
#   - the object index (shelby_objects) for uid, owner, size, commit time
#   - the contract view blob_metadata::get_blob_metadata for commitment,
#     slice, state and the payment epochs
#   - the payment epoch clock, to compute a "Paid until" date
#
#   NEW  frontend/src/lib/onchain.ts                    data layer + parsing
#   MOD  frontend/src/hooks/useOnChainBlob.ts           thin hook over it
#   MOD  frontend/src/components/video/OnChainProof.tsx new rows
#   MOD  frontend/src/lib/explorer.ts                   drops dead indexer URL
#
# Frontend only. No package changes, no backend changes.
#
#   ./vm_shelby_sdk09c.sh            apply (needs Part 1 + 1b applied)
#   ./vm_shelby_sdk09c.sh --force    apply even if local files differ from GitHub
#   ./vm_shelby_sdk09c.sh --revert   restore from the latest backup
#
# Run from the repo root (dir containing backend/ and frontend/).
# ============================================================================
set -euo pipefail

MARKER="vm_shelby09c"
STAMP="$(date +%Y%m%d-%H%M%S)"
BAKDIR=".vm_shelby09c_backups"
FE_PKG="frontend/package.json"
HK="frontend/src/hooks/useOnChainBlob.ts"
PF="frontend/src/components/video/OnChainProof.tsx"
EX="frontend/src/lib/explorer.ts"
OC="frontend/src/lib/onchain.ts"

say() { printf '  %s\n' "$1"; }
die() { printf 'ERROR: %s\n' "$1" >&2; exit 1; }
sha() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

for f in "$FE_PKG" "$HK" "$PF" "$EX"; do
  [ -f "$f" ] || die "$f not found. Run from repo root (dir with backend/ and frontend/)."
done

if [ "${1:-}" = "--revert" ]; then
  [ -d "$BAKDIR" ] || die "No backup dir. Nothing to revert."
  LATEST="$(ls -1d "$BAKDIR"/*/ 2>/dev/null | sort | tail -1)"
  [ -n "$LATEST" ] || die "No backups found."
  LATEST="${LATEST%/}"
  cp "$LATEST/useOnChainBlob.ts" "$HK"
  cp "$LATEST/OnChainProof.tsx"  "$PF"
  cp "$LATEST/explorer.ts"       "$EX"
  if [ -f "$LATEST/onchain.ts" ]; then cp "$LATEST/onchain.ts" "$OC"; else rm -f "$OC"; fi
  say "Reverted 3 files and removed/restored onchain.ts from $LATEST/"
  exit 0
fi

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if [ -f "$OC" ] && grep -q "$MARKER" "$OC" && grep -q "$MARKER" "$PF"; then
  say "Already applied ($MARKER marker present). Use --revert to undo."
  exit 0
fi

grep -q '"@shelby-protocol/sdk": "[^"]*0\.9' "$FE_PKG" || die "Part 1 is not applied (frontend is not on @shelby-protocol/sdk 0.9). Run ./vm_shelby_sdk09.sh first."

# ---- pre-image check: only replace files that match what was patched ----
