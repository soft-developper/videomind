# ============================================================================
# VideoMind: production API guard (Part 0, backend only)
# ============================================================================
# Closes the routes that acted on EVERY wallet when no wallet was sent,
# and caps the routes that spend money or delete records.
#
#   Before this patch, with no login of any kind:
#     DELETE /api/videos/all          deleted every video on the platform
#     GET    /api/videos              listed every video on the platform
#     POST   /api/chat/search/all     searched every wallet's transcripts
#     chat, search, learn, uploads    unlimited Whisper and Claude spend
#
#   NEW  backend/src/lib/guard.ts      wallet check + rate limits
#   MOD  backend/src/routes/videos.ts  wallet required, limits on upload/delete
#   MOD  backend/src/routes/chat.ts    AI limit, search needs a wallet
#   MOD  backend/src/routes/learn.ts   AI limit, wallet format check
#   MOD  backend/src/routes/stats.ts   zero counts without a wallet
#
# No frontend change. No new package. No database change.
#
# Still open after this patch: a caller who knows a wallet address can
# act as that wallet, inside the limits. Closing that needs wallet sign in
# (rebuild Part 1).
#
#   ./vm_api_guard.sh            apply
#   ./vm_api_guard.sh --force    apply even if local files differ from GitHub
#   ./vm_api_guard.sh --revert   restore from the latest backup
#
# Run from the repo root (dir containing backend/ and frontend/), on main.
# ============================================================================
