#!/usr/bin/env bash
# ============================================================================
# VideoMind - Shelby SDK 0.9 upgrade, Part 1 (upload fix)
# ============================================================================
# Fixes the wallet popup error on upload:
#   Simulation error: Type mismatch for argument 3, type 'vector<vector<u8>>'
#
# Cause: the Shelbynet blob_metadata contract dropped the expiry argument
# from register_multiple_blobs (shipped with @shelby-protocol/sdk 0.8.0).
# The app was pinned to sdk 0.6.0, which still sends expirationMicros as
# argument 3, where the contract now expects the merkle roots.
#
# What this does:
#   frontend: @shelby-protocol/sdk 0.6.0 -> 0.9.2, @shelby-protocol/react 4.1.0 -> 4.3.0
#   backend : @shelby-protocol/sdk 0.6.0 -> 0.9.2
#   UploadZone.tsx   drop expirationMicros from the upload call
#   ExpiryBanner.tsx useAccountBlobs -> useAccountObjects, banner switched OFF
#   RenewButton.tsx  switched OFF (renders nothing)
#   shelbyClient.ts  drop expirationMicros from client.upload
#
# Renewal UI is OFF on purpose. It is reworked in Part 2.
#
#   ./vm_shelby_sdk09.sh            apply
#   ./vm_shelby_sdk09.sh --force    apply even if local files differ from GitHub
#   ./vm_shelby_sdk09.sh --revert   restore everything from the latest backup
#
# Run from the repo root (dir containing backend/ and frontend/).
# ============================================================================
set -euo pipefail

SDK_VER="0.9.2"
REACT_VER="4.3.0"
MARKER="vm_shelby09"
STAMP="$(date +%Y%m%d-%H%M%S)"
BAKDIR=".vm_shelby09_backups"

FE_PKG="frontend/package.json";  FE_LOCK="frontend/package-lock.json"
BE_PKG="backend/package.json";   BE_LOCK="backend/package-lock.json"
UZ="frontend/src/components/upload/UploadZone.tsx"
EB="frontend/src/components/layout/ExpiryBanner.tsx"
RB="frontend/src/components/video/RenewButton.tsx"
SC="backend/src/lib/shelbyClient.ts"

say() { printf '  %s\n' "$1"; }
die() { printf 'ERROR: %s\n' "$1" >&2; exit 1; }
sha() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

for f in "$FE_PKG" "$FE_LOCK" "$BE_PKG" "$BE_LOCK" "$UZ" "$EB" "$RB" "$SC"; do
  [ -f "$f" ] || die "$f not found. Run from repo root (dir with backend/ and frontend/)."
done
command -v npm >/dev/null 2>&1 || die "npm not found on PATH."

# flat backup name for a repo path: frontend/package.json -> frontend__package.json
bname() { printf '%s' "$1" | sed 's#/#__#g'; }
ALL_FILES="$FE_PKG $FE_LOCK $BE_PKG $BE_LOCK $UZ $EB $RB $SC"

restore_from() {
  for f in $ALL_FILES; do cp "$1/$(bname "$f")" "$f"; done
}

if [ "${1:-}" = "--revert" ]; then
  [ -d "$BAKDIR" ] || die "No backup dir. Nothing to revert."
  LATEST="$(ls -1d "$BAKDIR"/*/ 2>/dev/null | sort | tail -1)"
  [ -n "$LATEST" ] || die "No backups found."
  restore_from "${LATEST%/}"
  say "Restored 8 files from $LATEST"
  say "Re-syncing node_modules to the restored lockfiles..."
  (cd frontend && npm ci --no-audit --no-fund) || die "frontend npm ci failed. Files are restored; run npm ci by hand."
  (cd backend  && npm ci --no-audit --no-fund) || die "backend npm ci failed. Files are restored; run npm ci by hand."
  say "Reverted."
  exit 0
fi

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if grep -q "$MARKER" "$UZ" 2>/dev/null && grep -q "\"@shelby-protocol/sdk\": \"[^\"]*$SDK_VER\"" "$FE_PKG" 2>/dev/null; then
  say "Already applied ($MARKER marker + sdk $SDK_VER present). Use --revert to undo."
  exit 0
fi

# ---- pre-image check: only replace files that match what was patched ----
PRE_UZ="95c6e73691e84d8b5559beb7cc442b00715d7e08dfaf44804a5e8c878496a0e6"
PRE_EB="bc76cdbbffe5298afd3c57b05e0b8ce3384718a966c29cd1125eff88e76f3544"
PRE_RB="202e98d54c14de68b5dfe72eb818427156e26b6c2d268ef53acb5d663e352666"
PRE_SC="0227949739a72d27efd3ea9ae292a7deff37384b920a4f6975ba03871efdf5ba"

check_pre() {
  if [ "$(sha "$1")" != "$2" ]; then
    if [ "$FORCE" = "1" ]; then say "WARNING: $1 differs from GitHub (e516adf). Overwriting (--force)."
    else die "$1 differs from the GitHub version this patch was built on (e516adf). Nothing changed. Push or stash local edits, or re-run with --force."; fi
  fi
}
check_pre "$UZ" "$PRE_UZ"; check_pre "$EB" "$PRE_EB"; check_pre "$RB" "$PRE_RB"; check_pre "$SC" "$PRE_SC"

