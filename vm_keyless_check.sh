#   ./vm_keyless_check.sh            apply (needs Part 12b on the branch)
#   ./vm_keyless_check.sh --force    apply even if the file differs from GitHub
#   ./vm_keyless_check.sh --revert   restore it from the latest backup
#
# Run from the repo root (dir containing backend/ and frontend/).
# ============================================================================
