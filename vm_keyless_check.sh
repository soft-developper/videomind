# ============================================================================
# VideoMind, Part 12c: checking the Google and Apple wallet signature
# ============================================================================
# FOR THE rebuild BRANCH. It refuses to run on main: apply it on rebuild,
# then fast forward main.
#
# After 12b the Google wallet's message is read correctly, but its proof
# was refused ("signature is not valid"). A Google or Apple wallet proves
# the account with a zero knowledge proof that needs the keyless settings
# and Google's or Apple's public key. They were read only from shelbynet.
# Now, if shelbynet cannot confirm it, the same official values are read
# from Aptos mainnet, then the provider's key straight from Google's or
# Apple's published list. Each failed attempt is written to the Render log
# with its reason ("[auth] keyless sign in ... not verified: ...").
#
#   BACKEND   1 changed (src/lib/auth.ts). Nothing to install
