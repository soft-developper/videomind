say() { printf '  %s\n' "$1"; }
die() { printf 'ERROR: %s\n' "$1" >&2; exit 1; }
sha() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}
bname() { printf '%s' "$1" | sed 's#/#__#g'; }

[ -d frontend ] && [ -d backend ] || die "Run from repo root (dir with backend/ and frontend/)."

BRANCH="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
if [ "$BRANCH" = "main" ]; then
  die "You are on main. This part is for the rebuild branch. Run: git checkout rebuild"
fi

restore_from() {
  local f
  for f in "${MOD[@]}"; do
    if [ -f "$1/$(bname "$f")" ]; then mkdir -p "$(dirname "$f")"; cp "$1/$(bname "$f")" "$f"; fi
  done
  for f in ${ADD[@]+"${ADD[@]}"}; do
    if [ -f "$1/$(bname "$f")" ]; then cp "$1/$(bname "$f")" "$f"; else rm -f "$f"; fi
  done
}

if [ "${1:-}" = "--revert" ]; then
  [ -d "$BAKDIR" ] || die "No backup dir. Nothing to revert."
  LATEST="$(ls -1d "$BAKDIR"/*/ 2>/dev/null | sort | tail -1)"
  [ -n "$LATEST" ] || die "No backups found."
  restore_from "${LATEST%/}"
  say "Restored 1 changed file, from $LATEST"
  exit 0
fi

FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if grep -q "$MARKER" "backend/src/lib/auth.ts"; then
  say "Already applied ($MARKER marker present). Use --revert to undo."
  exit 0
fi

grep -q "vm_keyless" backend/src/lib/auth.ts 2>/dev/null || die "Part 12b is not on this branch. Run: git pull origin rebuild"

# ---- pre image check: every file must match what this part was built on ----
check_pre() {
  [ -f "$1" ] || die "$1 not found. Nothing changed."
  if [ "$(sha "$1")" != "$2" ]; then
    if [ "$FORCE" = "1" ]; then say "WARNING: $1 differs from GitHub rebuild (6932344). Proceeding (--force)."
    else die "$1 differs from the GitHub rebuild version this part was built on (6932344). Nothing changed. Run git pull origin rebuild, push or stash local edits, or run again with --force."; fi
  fi
}
i=0; for f in "${MOD[@]}"; do check_pre "$f" "${PRE_MOD[$i]}"; i=$((i+1)); done
for f in ${ADD[@]+"${ADD[@]}"}; do
  if [ -f "$f" ] && [ "$FORCE" != "1" ]; then die "$f already exists but is not this part's version. Nothing changed. Run again with --force to overwrite it."; fi
done

